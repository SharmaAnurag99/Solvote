/**
 * Calculate merkle tree path for a voter (mock implementation)
 * In production, this comes from the backend/contract
 */
export const calculateMerkleProof = (
  voterId: string,
  treeDepth: number = 20
): { pathElements: string[]; pathIndices: number[] } => {
  // Mock: Generate pseudo-random path for demonstration
  const pathElements: string[] = [];
  const pathIndices: number[] = [];

  for (let i = 0; i < treeDepth; i++) {
    // Generate fake merkle proof hashes (would be real hashes in production)
    const hash = BigInt(voterId) * BigInt(i + 1);
    pathElements.push(hash.toString());
    pathIndices.push(Math.random() > 0.5 ? 1 : 0);
  }

  return { pathElements, pathIndices };
};
